void driverStart() {
  if (!zeus_gpu_sqe_size || !zeus_gpu_zap_mdt_size || !zeus_gpu_zap_b01_size) {printf("ZEUS GPU: stage 8 stop: GPU firmware not in this build\n"); return;}
  const uintptr_t smmu = gBase[W_SMMU], cb = smmu + 32 * 0x1000;
  // zeus DT: iommus = <&apps_smmu 0x0 0x400>, <&apps_smmu 0x1 0x400>. The kit writes and checks its routes with this mask.
  if (!&armsmmu4k_smr_mask) {printf("ZEUS GPU: stage 8 stop: SMMU kit without the SMR mask patch\n"); return;}
  armsmmu4k_smr_mask = 0x400;
  const IOReturn context = NativeAdrenoGpuContextBringup(reinterpret_cast<volatile uint8_t *>(smmu), kSize[W_SMMU], 0, 2, 0, 0, 1, 1, nullptr, &gContextReport);
  printf("ZEUS GPU: driver context %x step %u program %u attach %u spans %u mismatch %x\n", context, gContextReport.step, gContextReport.program_status,
         gContextReport.route_status, gContextReport.spans, gContextReport.mismatch);
  if (context) {
    // Which attach phase refused (1 global/context/scan, 2 slot writes, 3 observe) and what the slots and bank 0 hold now.
    printf("ZEUS GPU: driver route phase %u writes %u verified %u; program phase %u writes %u enabled %u\n", gContextReport.route_phase,
           gContextReport.route_writes, gContextReport.routes_verified, gContextReport.program_phase, gContextReport.program_writes,
           gContextReport.program_enabled);
    for (unsigned slot = 0; slot < 4; ++slot)
      printf("ZEUS GPU: driver slot %u smr %08x s2cr %08x\n", slot, rd32(smmu + 0x800 + 4 * slot), rd32(smmu + 0xc00 + 4 * slot));
    printf("ZEUS GPU: driver bank 0 sctlr %08x cbar %08x fsr %08x scr0 %08x\n", rd32(cb), rd32(smmu + 0x1000 + 0x0), rd32(cb + 0x58), rd32(smmu));
    return;
  }
  // The GPU streams' SMR mask 0x400 (zeus DT) is written by the kit itself (armsmmu4k_smr_mask, set above): a rewrite here made
  // every later route check of the kit fail, so no per-process address space could attach (boot-smmudiag, 2026-11-19).
  wr32(cb + 0x4, 0x32b);
  wr32(cb + 0x618, 0);
  wr32(cb + 0x7f0, 0);
  for (unsigned i = 0; (rd32(cb + 0x7f4) & 1) && i < 2000; ++i) IODelay(1);
  if (NativeAdrenoGpuContextBuffers(gBuffers)) {printf("ZEUS GPU: driver buffers refused\n"); return;}
  for (unsigned i = 0; i < GpuBufferCount; ++i) {
    OSSharedPtr<IODeviceMemory> memory(IODeviceMemory::withRange(gBuffers[i].physical, gBuffers[i].bytes), OSNoRetain);
    if (memory) gMaps[i] = OSSharedPtr<IOMemoryMap>(memory->map(kIOMapAnywhere | kIOMapWriteCombineCache), OSNoRetain);
    if (!gMaps[i]) {printf("ZEUS GPU: driver buffer %u not mapped\n", i); return;}
    gCpu[i] = reinterpret_cast<volatile uint8_t *>(gMaps[i]->getVirtualAddress());
  }
  if (zeus_gpu_sqe_size - 4 > gBuffers[0].bytes) {printf("ZEUS GPU: SQE too large\n"); return;}
  for (size_t i = 4; i < zeus_gpu_sqe_size; ++i) gCpu[0][i - 4] = zeus_gpu_sqe[i];
  ringBarrier(nullptr);
  coreHwInit();
  gpuWr(kRbbmIntMask, kA730IntMask);
  gpuWr64(CP_SQE_INSTR_BASE, gBuffers[0].iova);
  const IOReturn attached = gDriverRing.attach(&kRingIo, &kRingCache, const_cast<uint8_t *>(gCpu[1]), gBuffers[1].bytes, gBuffers[1].iova,
                                         const_cast<uint8_t *>(gCpu[2]), gBuffers[2].bytes, gBuffers[2].iova);
  printf("ZEUS GPU: driver ring attach %x\n", attached);
  if (attached) return;
  gpuWr64(kCpBvRptrAddr, gBuffers[2].iova + 8);
  gpuWr(CP_SQE_CNTL, 1);
  size_t written = 0;
  const NativeAdrenoPwrupCounts counts = {0, 0, 0};
  const IOReturn list = NativeAdrenoPwrupList::pack(counts, nullptr, nullptr, nullptr, nullptr, nullptr, const_cast<uint8_t *>(gCpu[3]), gBuffers[3].bytes, &written);
  ringBarrier(nullptr);
  const NativeAdrenoCpInitConfig config = {gBuffers[0].iova, gBuffers[3].iova, 1};
  uint32_t fence = 0, seen = 0;
  const IOReturn init = list ? list : gCpInit.run(&kRingIo, &gDriverRing, &config, &fence);
  const IOReturn waited = init ? init : gDriverRing.wait(fence, &kRingClock, 200000, &seen);
  printf("ZEUS GPU: driver CP init list %x run %x wait %x fence %u seen %u\n", list, init, waited, fence, seen);
  if (waited) {coreReport("driver CP init failed"); return;}
  if (!loadZap()) {printf("ZEUS GPU: stage 8 stop: zap shader refused\n"); return;}
  uint32_t secure[2] = {};
  if (AdrenoPM4Type7(0x66, 1, &secure[0]) != AdrenoPM4Success || !ringFence("secure exit", secure, 2)) {coreReport("secure exit failed"); return;}
  gZapRunning = true;
  volatile uint32_t *scratch = reinterpret_cast<volatile uint32_t *>(gCpu[4]);
  scratch[0] = 0;
  ringBarrier(nullptr);
  uint32_t write[4] = {};
  if (AdrenoPM4Type7(0x3d, 3, &write[0]) != AdrenoPM4Success) return;
  write[1] = uint32_t(gBuffers[4].iova); write[2] = uint32_t(gBuffers[4].iova >> 32); write[3] = 0x600dc0de;
  if (!ringFence("memory write", write, 4)) {coreReport("memory write failed"); return;}
  printf("ZEUS GPU: driver scratch %08x\n", scratch[0]);
  if (scratch[0] != 0x600dc0de) return;
  uint32_t readback = 0; uint64_t router = 0;
  const IOReturn irq = armcpu_spi_attach ? armcpu_spi_attach(332, false, driverIrq, nullptr, &readback, &router) : kIOReturnUnsupported;
  uint32_t nop = 0;
  const bool nopFence = AdrenoPM4Type7(0x10, 0, &nop) == AdrenoPM4Success && ringFence("nop", &nop, 1);
  IOSleep(20);
  printf("ZEUS GPU: irq attach %x readback %x router %llx fence %u count %u seen %08x status %08x\n", irq, readback, router, nopFence, gIrqCount, gIrqSeen, gpuRd(kRbbmIntStatus));
  openCpAperture();
  NativeAdrenoVm *vm = NativeAdrenoGpuContextVm();
  const IOReturn submit = vm ? gSubmit.attach(vm, &gDriverRing) : kIOReturnNotReady;
  const IOReturn timer = gTimer.attach(&kTimerIo, NativeAdrenoTimeCp);
  // sheng installs the DRAM reader before its coherence probe; zeus's probe has its own page reader, so order does not matter here.
  if (!gDramReadLock) gDramReadLock = IOLockAlloc();
  if (gDramReadLock) native_adreno_dram_read32 = dramRead32;
  if (!submit) coherenceProbe(vm);   // before any client, as sheng: decides how imported user memory is mapped
  // The restart hook before publication, as sheng: a hang then restarts the GPU and replays the other submissions.
  if (native_adreno_set_restart) native_adreno_set_restart(gpuRestart, nullptr);
  printf("ZEUS GPU: restart hook %s\n", native_adreno_set_restart ? "installed" : "missing");
  void *handle = OSMetaClass::preModLoad(g_kernel_kmod_info.name);
  if (!handle) {printf("ZEUS GPU: driver class registration not available\n"); return;}
  native_adreno_publish_static_init();
  const OSReturn classes = OSMetaClass::postModLoad(handle);
  const unsigned ias = NativeAdrenoGpuContextInputBits();
  gDeviceInfo.va_size = ias > 32 ? (1ull << ias) - GpuClientVaStart : 0;
  const IOReturn published = submit || classes ? kIOReturnNotReady : native_adreno_publish(vm, &gSubmit, &gDriverRing, &kRingClock, timer ? nullptr : &gTimer, &gDeviceInfo, ias, 40);
  printf("ZEUS GPU: driver submit %x timer %x classes %x publish %x ias %u service %p\n", submit, timer, classes, published, ias, native_adreno_published_service());
  if (!published && native_adreno_published_service()) printf("ZEUS GPU: DRIVER PUBLISHED\n");
  coreReport("after publish");
  if (!published && gMetal) publishMetal();
}

void run(unsigned mode) {
  unsigned have = 0;
  for (unsigned i = 0; i < (mode >= 5 ? kWindows : kBaseWindows); ++i) {
    gBase[i] = mapIo(kPhys[i], kSize[i]);
    if (gBase[i]) have |= 1u << i;
  }
  printf("ZEUS GPU: mode %u, windows mapped 0x%x\n", mode, have);
  static gpb_result r;
  static gpb_gmu_clocks k;
  const gpb_io &io = kIo;
  gpb_run(&io, mode > 3 ? 3 : mode, have, &r);
  printf("ZEUS GPU: stages gcc %s cc %s smmu %s gpu %s, io error %d\n", gpb_state_text(r.gcc), gpb_state_text(r.cc),
         gpb_state_text(r.smmu), gpb_state_text(r.gpu), r.io_error);
  printf("ZEUS GPU: gcc cfg_ahb %08x -> %08x memnoc %08x dvm %08x vote %08x\n", r.cfg_ahb, r.cfg_ahb_after, r.memnoc, r.dvm, r.pll_vote);
  printf("ZEUS GPU: gpucc cx %08x -> %08x (hw %08x, powered %u) gx %08x ahb %08x smmu %08x -> %08x (clocks %u) gmu %08x\n", r.cx_before,
         r.cx_gdscr, r.cx_hwctrl, r.powered_cx, r.gx_gdscr, r.cc_ahb, r.cc_smmu_before, r.cc_smmu, r.powered_clocks, r.cc_gmu);
  printf("ZEUS GPU: smmu scr0 %08x id0 %08x id1 %08x id2 %08x gfsr %08x smr valid %u first %x = %08x s2cr %08x\n", r.scr0, r.id0, r.id1,
         r.id2, r.gfsr, r.smr_valid, r.smr_first, r.smr_first_val, r.s2cr_first_val);
  printf("ZEUS GPU: rbbm_status %08x\n", r.rbbm_status);
  gpb_read_gmu_clocks(&io, &r, &k);
  printf("ZEUS GPU: gmu clocks read %d pll1 mode %08x op %08x l %08x user %08x | gmu rcg %08x/%08x hub rcg %08x/%08x\n", k.done, k.pll1_mode,
         k.pll1_opmode, k.pll1_l, k.pll1_user, k.gmu_cmd, k.gmu_cfg, k.hub_cmd, k.hub_cfg);
  printf("ZEUS GPU: branches cx_gmu %08x cxo %08x hub_cx_int %08x demet %08x axi %08x memnoc %08x gpll0 vote %08x\n", k.cx_gmu, k.cxo,
         k.hub_cx_int, k.demet, k.axi, k.memnoc, k.gpll0_vote);
  if (mode >= 4 && gmuClocks(r) && mode >= 5) {
    gmuStart();
    if (mode >= 6 && gGmuReady) gmuHfiAndGx();
    if (mode == 7 && gGxOn) coreStart();
    if (mode >= 8 && gGxOn) driverStart();
  }
  printf("ZEUS GPU: next block AOP command DB\n");
  IOSleep(gPauseMs);
  if (const uintptr_t db = mapIo(kCmdDb, 0x1000))
    printf("ZEUS GPU: cmd-db version %08x magic %08x (expect 0c0330db)\n", rd32(db), rd32(db + 4));
  printf("ZEUS GPU: done\n");
}

// GPU clock governor (`gpu-dcvs=1`), after sheng's (GpuPowerProbe.cpp, BSD-2-Clause-Patent). gpum33: the boot vote held 818 MHz for the
// whole boot and the firmware limited the CPU clusters to a third of their vote under load. The GMU's XO power counter 0 counts 19.2 MHz
// ticks while the GPU is busy (AO CX_BUSY_MASK 0xff000000, SELECT_0 low byte 0x20, ENABLE 1: adreno_gen7.c, same on the A730). Every
// 16 ms: to the top when a window was over 85 % busy; up to the lowest level that keeps it 50 % busy; down one level after 4 windows
// that needed at most 0.8 x the next lower one; to the floor (`gpu-dcvs-min`, default 3) after 80 ms without work. Highest level:
// gpu-level. Each level's bandwidth is the zeus device tree's qcom,bus-freq, at most gpu-dcvs-bw (default 11). A busy counter that never
// moves while the ring holds work (64 windows) puts the boot level back and ends the governor. A failed vote is counted, and eight in a
// row end it. Nothing here prints: ioWrite and hfiSend do, and the console is slow.
constexpr unsigned kDcvsTop = 12;
constexpr uint32_t kDcvsMHz[kDcvsTop + 1] = {0, 220, 285, 317, 350, 421, 492, 545, 599, 640, 734, 791, 818};
constexpr uint8_t kDcvsBw[kDcvsTop + 1] = {0, 2, 2, 2, 3, 6, 6, 8, 8, 10, 10, 11, 11};
uint32_t gmuQuietRd(uint32_t dword) {return rd32(gBase[W_GMU] + dword * 4 - 0x68000);}
void gmuQuietWr(uint32_t dword, uint32_t v) {wr32(gBase[W_GMU] + dword * 4 - 0x68000, v);}
// hfiSend's exchange without its prints and its long busy waits: sleeps 1 ms between looks, 50 ms at most.
bool dcvsVote(unsigned level, unsigned bw) {
  volatile uint32_t *m = reinterpret_cast<volatile uint32_t *>(gHfi.cpu), *cmdq = m + 6, *rspq = m + 18;
  volatile uint32_t *cmd = m + 212, *rsp = m + 212 + kQueueWords;
  cleanCache(gHfi.cpu, gHfi.bytes);
  uint32_t write = cmdq[11];
  if (write >= kQueueWords || (write & 3)) return false;
  const uint32_t sequence = (++gHfiSequence) % 0xfff;
  const uint32_t words[4] = {(sequence << 20) | (4u << 8) | 30, 1, level, bw};
  for (unsigned i = 0; i < 4; ++i) cmd[(write + i) & (kQueueWords - 1)] = words[i];
  cmdq[11] = (write + 4) & (kQueueWords - 1);
  cleanCache(gHfi.cpu, gHfi.bytes);
  gmuQuietWr(HOST2GMU_INTR_SET, 1);
  for (unsigned tries = 0; tries < 50; ++tries) {
    IOSleep(1);
    if (!(gmuQuietRd(GMU2HOST_INTR_INFO) & 1)) continue;
    gmuQuietWr(GMU2HOST_INTR_CLR, 1);
    cleanCache(gHfi.cpu, gHfi.bytes);
    while (rspq[10] != rspq[11]) {
      const uint32_t read = rspq[10];
      if (read >= kQueueWords) return false;
      const uint32_t first = rsp[read], n = (first >> 8) & 255;
      if (!n || n > 32) return false;
      const uint32_t ack = rsp[(read + 1) & (kQueueWords - 1)], error = rsp[(read + 2) & (kQueueWords - 1)];
      rspq[10] = (read + ((n + 3) & ~3u)) & (kQueueWords - 1);
      cleanCache(gHfi.cpu, 0x100);
      if ((first & 255) == 100 || ((first >> 16) & 15) != 1 || (ack >> 20) != sequence) continue;
      return error == 0;
    }
  }
  return false;
}
uint64_t dcvsBusyTicks() {
  const uint32_t hi = gmuQuietRd(0x1f845);
  uint32_t lo = gmuQuietRd(0x1f844);
  const uint32_t hi2 = gmuQuietRd(0x1f845);
  if (hi2 != hi) lo = gmuQuietRd(0x1f844);
  return uint64_t(hi2) << 32 | lo;
}
// TSENS v2 (zeus device tree): TM_Sn_STATUS at +0xa0 + 4n, bits 11:0 signed 0.1 C, bit 21 valid. Read only.
uintptr_t gTsens[2];
void thermalRead() {
  auto hottest = [](unsigned c, unsigned first, unsigned last) {
    int32_t max = 0x7fffffff;
    for (unsigned i = first; gTsens[c] && i <= last; ++i) {
      const uint32_t v = rd32(gTsens[c] + 0xa0 + 4 * i);
      const int32_t t = (int32_t(v & 0xfff) ^ 0x800) - 0x800;
      if ((v & (1u << 21)) && (max == 0x7fffffff || t > max)) max = t;
    }
    return max;
  };
  const int32_t now[3] = {hottest(0, 14, 14), hottest(0, 5, 13), hottest(1, 1, 4)};
  for (unsigned i = 0; i < 3; ++i) {
    zeus_thermal[i] = now[i];
    if (now[i] != 0x7fffffff && (zeus_thermal[3 + i] == 0x7fffffff || now[i] > zeus_thermal[3 + i])) zeus_thermal[3 + i] = now[i];
  }
}
struct TopProc {int pid; uint64_t last, delta; char name[18];};
struct TopScan {TopProc *p; unsigned n, max;};
void topOne(TopScan *s, int pid, void *task, const char *name) {
  if (!task) return;
  ZeusTaskInfo info{};
  fill_taskprocinfo(static_cast<task_t>(task), &info);
  const uint64_t total = info.user + info.system;
  for (unsigned i = 0; i < s->n; ++i) if (s->p[i].pid == pid) {
    s->p[i].delta = total > s->p[i].last ? total - s->p[i].last : 0; s->p[i].last = total;
    return;
  }
  if (s->n == s->max) return;
  TopProc &t = s->p[s->n++];
  t.pid = pid; t.last = total; t.delta = 0;
  strlcpy(t.name, name ? name : "?", sizeof t.name);
}
int topScan(void *proc, void *arg) {
  topOne(static_cast<TopScan *>(arg), proc_pid(static_cast<struct proc *>(proc)), proc_task(static_cast<struct proc *>(proc)), proc_name_address(proc));
  return 0;   // PROC_RETURNED
}
void topThread(void *, wait_result_t) {
  thread_set_thread_name(current_thread(), "zeus-top");
  TopScan s{static_cast<TopProc *>(IOMallocZero(sizeof(TopProc) * 512)), 0, 512};
  if (!s.p) return;
  uint64_t last = mach_absolute_time();
  for (;;) {
    IOSleep(6000);
    for (unsigned i = 0; i < s.n; ++i) s.p[i].delta = 0;
    topOne(&s, 0, kernel_task, "kernel");
    proc_iterate(1 /* PROC_ALLPROCLIST */, topScan, &s, nullptr, nullptr);
    const uint64_t now = mach_absolute_time();
    uint64_t ns = 0;
    absolutetime_to_nanoseconds(now - last, &ns);
    last = now;
    char row[sizeof zeus_top_row];
    int n = snprintf(row, sizeof row, "#top %llums", static_cast<unsigned long long>(ns / 1000000));
    uint64_t rest = 0;
    for (unsigned k = 0; k < 10; ++k) {
      TopProc *best = nullptr;
      for (unsigned i = 0; i < s.n; ++i) if (s.p[i].delta && (!best || s.p[i].delta > best->delta)) best = &s.p[i];
      if (!best || n < 0 || n >= int(sizeof row) - 32) break;
      absolutetime_to_nanoseconds(best->delta, &ns);
      best->delta = 0;
      n += snprintf(row + n, sizeof row - n, " %s:%llu", best->name, static_cast<unsigned long long>(ns / 1000000));
    }
    for (unsigned i = 0; i < s.n; ++i) {absolutetime_to_nanoseconds(s.p[i].delta, &ns); rest += ns;}
    if (n > 0 && n < int(sizeof row)) snprintf(row + n, sizeof row - n, " rest:%llu", static_cast<unsigned long long>(rest / 1000000));
    strlcpy(zeus_top_row, row, sizeof zeus_top_row);
    if (s.n == s.max) s.n = 0;   // pids of ended processes: start over
  }
}
void dcvsThread(void *, wait_result_t) {
  thread_set_thread_name(current_thread(), "zeus-gpu-dcvs");
  gTsens[0] = mapIo(0x0c263000, 0x1000);
  gTsens[1] = mapIo(0x0c265000, 0x1000);
  unsigned on = 0, floor = 3;
  PE_parse_boot_argn("gpu-dcvs", &on, sizeof on);
  PE_parse_boot_argn("gpu-dcvs-min", &floor, sizeof floor);
  const unsigned top = gBootLevel;
  if (floor < 1) floor = 1;
  if (floor > top) floor = top;
  if (on) {
    gmuQuietWr(0x23b0e, 0xff000000u);
    gmuQuietWr(0x1f841, (gmuQuietRd(0x1f841) & ~0xffu) | 0x20);
    gmuQuietWr(0x1f840, 1);
    zeus_gpu_dcvs[0] = 1;
  }
  unsigned cur = top, down = 0, dead = 0, failed = 0, rest = 0, windows = 0;
  bool moved = false;
  zeus_gpu_dcvs[1] = cur;
  uint64_t lastBusy = on ? dcvsBusyTicks() : 0, lastT = mach_absolute_time(), sumBusy = 0, sumNs = 0, at[kDcvsTop + 1] = {};
  for (unsigned tick = 0;; ++tick) {
    IOSleep(on ? 16 : 1000);
    if (!on || !(tick & 63)) thermalRead();
    if (!on) continue;
    const uint64_t busy = dcvsBusyTicks(), t = mach_absolute_time();
    uint64_t ns = 0;
    absolutetime_to_nanoseconds(t - lastT, &ns);
    uint64_t busyNs = (busy - lastBusy) * 625 / 12;   // 52.083 ns per XO tick
    const bool work = gpuRd(CP_RB_RPTR) != gpuRd(CP_RB_WPTR);
    lastBusy = busy; lastT = t;
    if (!ns) continue;
    if (busyNs > ns) busyNs = ns;
    if (busyNs * 100 >= ns) moved = true;
    if (!moved && work && ++dead >= 64) {
      zeus_gpu_dcvs[0] = 2;
      dcvsVote(gBootLevel, gBootBw);
      on = 0;
      continue;
    }
    if (!moved) continue;   // the boot level stays until the counter has shown work
    sumBusy += busyNs; sumNs += ns; at[cur] += ns; ++windows;
    const bool active = busyNs * 100 >= ns || work;
    const uint64_t need = busyNs * kDcvsMHz[cur] * 2 / ns;
    unsigned want = cur, level = 1;
    while (level < top && kDcvsMHz[level] < need * 11 / 10) ++level;
    if (busyNs * 100 > ns * 85) want = top;
    else if (level > cur) want = level;
    else if (active) {
      if (cur > floor && need * 10 <= uint64_t(kDcvsMHz[cur - 1]) * 8) {if (++down >= 4) want = cur - 1;}
      else down = 0;
    }
    rest = active ? 0 : rest + 1;
    if (rest >= 5) want = floor;
    if (want < floor) want = floor;
    if (want != cur) {
      const unsigned bw = kDcvsBw[want] > gBwCap ? gBwCap : kDcvsBw[want];
      if (dcvsVote(want, bw)) {cur = want; failed = 0; zeus_gpu_dcvs[1] = cur; zeus_gpu_dcvs[2] = zeus_gpu_dcvs[2] + 1;}
      else {
        zeus_gpu_dcvs[3] = zeus_gpu_dcvs[3] + 1;
        if (++failed >= 8) {zeus_gpu_dcvs[0] = 3; on = 0; continue;}
      }
      down = 0;
    }
    if (sumNs >= 10000000000ull) {
      zeus_gpu_dcvs[4] = uint32_t(sumBusy * 100 / sumNs);
      zeus_gpu_dcvs[5] = windows;
      for (unsigned l = 1; l <= kDcvsTop; ++l) {zeus_gpu_dcvs[5 + l] = uint32_t(at[l] * 100 / sumNs); at[l] = 0;}
      sumBusy = sumNs = windows = 0;
    }
  }
}
// The saved user state of a thread (struct arm_saved_state: an 8-byte header, then arm_saved_state64 x[29], fp, lr, sp, pc). Read in
// task_act_iterate_wth_args' callback, under the task lock: only plain loads, no faults. The first thread iterated is the main thread.
struct UstackRegs {unsigned threads; uint64_t x0, x1, x16, fp, lr, sp, pc;};
void ustackOne(thread_t thread, void *arg) {
  UstackRegs *r = static_cast<UstackRegs *>(arg);
  if (r->threads++) return;
  const uint8_t *s = static_cast<const uint8_t *>(find_user_regs(thread));
  if (!s) return;
  const uint64_t *x = reinterpret_cast<const uint64_t *>(s + 8);
  r->x0 = x[0]; r->x1 = x[1]; r->x16 = x[16]; r->fp = x[29]; r->lr = x[30]; r->sp = x[31]; r->pc = x[32];
}
void ustackThread(void *arg, wait_result_t) {
  thread_set_thread_name(current_thread(), "zeus-ustack");
  const int pid = static_cast<int>(reinterpret_cast<uintptr_t>(arg));
  const uint64_t kUser = 0x0000000fffffffffULL;   // user addresses below 64 GiB; strips PAC bits
  unsigned same = 0;
  uint64_t lastPc = 0;
  for (;;) {
    IOSleep(10000);
    struct proc *p = proc_find(pid);
    if (!p) continue;
    task_t task = reinterpret_cast<task_t>(proc_task(p));
    UstackRegs r{};
    char name[20] = "?";
    if (const char *n = proc_name_address(p)) strlcpy(name, n, sizeof name);
    uint64_t frames[22];
    unsigned nf = 0;
    if (task) {
      task_act_iterate_wth_args(task, ustackOne, &r);
      vm_map_t map = get_task_map_reference(task);
      uint64_t fp = r.fp & kUser;
      while (map && fp && !(fp & 7) && nf < 22) {
        uint64_t pair[2] = {};
        if (vm_map_read_user(map, fp, pair, sizeof pair) != KERN_SUCCESS) break;
        frames[nf++] = pair[1] & kUser;
        const uint64_t next = pair[0] & kUser;
        if (next <= fp) break;
        fp = next;
      }
      if (map) vm_map_deallocate(map);
    }
    proc_rele(p);
    same = (r.pc & kUser) == lastPc ? same + 1 : 0;
    lastPc = r.pc & kUser;
    uint64_t ns = 0;
    absolutetime_to_nanoseconds(mach_absolute_time(), &ns);
    char row[sizeof zeus_ustack_row];
    int n = snprintf(row, sizeof row, "#ustack %d %s up %llus thr %u same %u x16 %lld x0 %llx x1 %llx pc %llx lr %llx sp %llx |", pid, name,
                     static_cast<unsigned long long>(ns / 1000000000ULL), r.threads, same, static_cast<long long>(r.x16),
                     static_cast<unsigned long long>(r.x0), static_cast<unsigned long long>(r.x1), static_cast<unsigned long long>(r.pc & kUser),
                     static_cast<unsigned long long>(r.lr & kUser), static_cast<unsigned long long>(r.sp & kUser));
    for (unsigned i = 0; i < nf && n > 0 && n < int(sizeof row) - 12; ++i)
      n += snprintf(row + n, sizeof row - n, " %llx", static_cast<unsigned long long>(frames[i]));
    strlcpy(zeus_ustack_row, row, sizeof zeus_ustack_row);
  }
}
void startUstack() {
  unsigned pid = 0;
  if (!PE_parse_boot_argn("zeus-ustack", &pid, sizeof(pid)) || !pid) return;
  thread_t thread;
  if (kernel_thread_start(ustackThread, reinterpret_cast<void *>(static_cast<uintptr_t>(pid)), &thread) == KERN_SUCCESS)
    thread_deallocate(thread);
}
void startDcvs() {
  thread_t thread;
  if (kernel_thread_start(dcvsThread, nullptr, &thread) == KERN_SUCCESS) thread_deallocate(thread);
  // The #top thread is opt-in (zeus-top=1). With it on, gpum37/38/39 logged a negative attrlistbulk time on the system volume
  // ("disk7s1 Spent too much time (18446744073709)s ... stop iterating") and SpringBoard stalled at the Apple logo. gpum40
  // (gpum39 without gpu-dcvs=1, so no #top thread) reached the home screen.
  unsigned top = 0;
  PE_parse_boot_argn("zeus-top", &top, sizeof(top));
  if (top && kernel_thread_start(topThread, nullptr, &thread) == KERN_SUCCESS) thread_deallocate(thread);
}

unsigned gMode, gDelayS = 90;
void probeThread(void *, wait_result_t) {
  thread_set_thread_name(current_thread(), "zeus-gpu-probe");
  startUstack();   // zeus-ustack=<pid> only
  IOSleep(gDelayS * 1000);
  run(gMode);
  if (gMetalStage == 5) startDcvs();   // gpu-dcvs=1 governs; without it the thread only reads the temperatures
  // After a published accelerator: report Metal discovery every 30 s for 10 minutes.
  for (unsigned round = 1; gMetalStage == 5 && round <= 20; ++round) {
    IOSleep(30000);
    metalReport(round);
  }
  thread_terminate(current_thread());
}
