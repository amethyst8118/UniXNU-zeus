void coreStart() {
  if (!zeus_gpu_sqe_size || !zeus_gpu_zap_mdt_size || !zeus_gpu_zap_b01_size) {printf("ZEUS GPU: stage 7 stop: GPU firmware not in this build\n"); return;}
  printf("ZEUS GPU: stage 7, sqe %lu bytes; PLL0 mode %08x op %08x l %08x\n", zeus_gpu_sqe_size, reg(GPB_WIN_GPUCC, 0), reg(GPB_WIN_GPUCC, 4), reg(GPB_WIN_GPUCC, 0x10));
  const uintptr_t smmu = gBase[W_SMMU], cb = smmu + 32 * 0x1000;
  if ((rd32(cb) & 1) || (rd32(smmu + 0x800) >> 31) || (rd32(smmu + 0x804) >> 31)) {printf("ZEUS GPU: stage 7 stop: SMMU bank 0 or stream slots busy\n"); return;}
  if (!dmaAlloc(gCoreTables, kTablePages * 4096) || !dmaAlloc(gRing, kRingBytes) || !dmaAlloc(gSqe, (zeus_gpu_sqe_size + 4095) & ~size_t(4095)) || !dmaAlloc(gScratch, 4096)) {
    printf("ZEUS GPU: stage 7 stop: no memory\n");
    return;
  }
  memcpy(gSqe.cpu, zeus_gpu_sqe + 4, zeus_gpu_sqe_size - 4);   // the first word of the file is not microcode
  cleanCache(gSqe.cpu, gSqe.bytes);
  const Dma gmuTables = gTables;
  const unsigned gmuUsed = gTablesUsed;
  gTables = gCoreTables;
  gTablesUsed = 1;
  const uint64_t page = (1ULL << 11) | (1ULL << 10) | (2ULL << 8) | (1ULL << 6) | 3;
  const bool mapped = mapRange(kRingIova, gRing, page) && mapRange(kSqeIova, gSqe, page | (1ULL << 7)) && mapRange(kScratchIova, gScratch, page);
  gTables = gmuTables;
  gTablesUsed = gmuUsed;
  if (!mapped) {printf("ZEUS GPU: stage 7 stop: GPU page tables do not fit\n"); return;}
  cleanCache(gCoreTables.cpu, gCoreTables.bytes);
  wr32(cb, 0);
  wr32(smmu + 0x1000 + 0x800, 1);
  wr32(smmu + 0x1000, 0x1f300);
  wr32(cb + 0x4, 0x32b);
  wr32(cb + 0x10, 0x38071);
  wr32(cb + 0x30, 0x80802020);
  wr64(cb + 0x20, (2ULL << 48) | gCoreTables.pa);
  wr64(cb + 0x28, 2ULL << 48);
  wr32(cb + 0x38, 0xff44);
  wr32(cb + 0x3c, 0);
  wr32(cb + 0x58, 0xffffffffu);
  wr32(cb + 0x618, 0);
  wr32(cb + 0x7f0, 0);
  for (unsigned i = 0; (rd32(cb + 0x7f4) & 1) && i < 2000; ++i) IODelay(1);
  wr32(cb, 0x127);
  for (uint32_t sid = 0; sid < 2; ++sid) {
    wr32(smmu + 0xc00 + 4 * sid, 2u << 16);
    wr32(smmu + 0x800 + 4 * sid, (1u << 31) | (0x400u << 16) | sid);
    wr32(smmu + 0xc00 + 4 * sid, 0);
  }
  printf("ZEUS GPU: GPU SMMU context bank 0 on\n");
  coreHwInit();
  gpuWr64(CP_SQE_INSTR_BASE, kSqeIova);
  gpuWr64(CP_RB_BASE, kRingIova);
  gpuWr(CP_RB_CNTL, 12u | (2u << 8) | (1u << 27));
  gpuWr64(CP_RB_RPTR_ADDR, kScratchIova + 0x80);
  gpuWr64(0xa98, kScratchIova + 0x100);
  gpuWr(CP_SQE_CNTL, 1);
  IOSleep(20);
  coreReport("after SQE start");
  if (coreFaulted()) return;
  ringPacket(0x17, 1);    // CP_THREAD_CONTROL
  ringWord(1u << 27);
  ringPacket(0x48, 7);    // CP_ME_INIT
  ringWord((1u << 0) | (1u << 1) | (1u << 3) | (1u << 6));
  ringWord(3);
  ringWord(0x20000000);
  ringWord(2);
  ringWord(0);
  ringWord(0);
  ringWord(0);
  if (!ringRun("CP_ME_INIT")) return;
  printf("ZEUS GPU: CP TAKES COMMANDS\n");
  if (!loadZap()) {printf("ZEUS GPU: stage 7 stop: zap shader refused\n"); return;}
  printf("ZEUS GPU: ZAP SHADER RUNS\n");
  ringPacket(0x66, 1);    // CP_SET_SECURE_MODE
  ringWord(0);
  if (!ringRun("CP_SET_SECURE_MODE 0")) return;
  ringPacket(0x3d, 3);    // CP_MEM_WRITE
  ringWord(kScratchIova);
  ringWord(0);
  ringWord(0x600dc0de);
  if (!ringRun("CP_MEM_WRITE")) return;
  cleanCache(gScratch.cpu, 64);
  const uint32_t word = *reinterpret_cast<volatile uint32_t *>(gScratch.cpu);
  printf("ZEUS GPU: scratch %08x (%s)\n", word, word == 0x600dc0de ? "GPU WROTE OUR MEMORY" : "wrong value");
}

