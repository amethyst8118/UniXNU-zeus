"""Make patches/xnu-12377/zeus-bind-enc.patch: the render server's Metal encoder thread on one CPU (run on the Mac).

usage: python3 mk-bind-enc-patch.py XNU_WORK_TREE OUT.patch
XNU_WORK_TREE is the build's patched xnu source (out/.../tree/.cache/xnu-work) WITHOUT this patch; the patch is last in the series.

Boot arg zeus-bind-enc=<cpu> (default off; 7 is the X2): when a thread of backboardd names itself "native-metal-encode" (the plug-in's
encode thread) it is bound to that CPU, if the CPU is online. Only the calling thread, once, outside every lock.
"""
import difflib
import sys
from pathlib import Path

tree, out = Path(sys.argv[1]), Path(sys.argv[2])
edits = {}


def edit(rel, pairs):
    src = (tree / rel).read_text()
    new = src
    for old, rep in pairs:
        assert new.count(old) == 1, (rel, old[:70], new.count(old))
        new = new.replace(old, rep)
    edits[rel] = (src, new)


edit('osfmk/kern/sched_prim.c', [
    ('void\nthread_bind_during_wakeup(thread_t thread, processor_t processor)\n{\n',
     '''/* zeus zeus-bind-enc=<cpu>: bind the calling thread to a CPU that is online (proc_info.c, PROC_SELFSET_THREADNAME). */
extern int zeus_bind_enc_cpu(void);
extern bool zeus_bind_self(int cpu);
extern boolean_t PE_parse_boot_argn(const char *arg_string, void *arg_ptr, int max_arg);
int
zeus_bind_enc_cpu(void)
{
	static int cached = -2;
	if (cached == -2) {
		int cpu = -1;
		if (!PE_parse_boot_argn("zeus-bind-enc", &cpu, sizeof(cpu)) || cpu <= 0 || cpu >= MAX_CPUS) {
			cpu = -1;
		}
		cached = cpu;
	}
	return cached;
}
bool
zeus_bind_self(int cpu)
{
	processor_t processor = cpu_to_processor(cpu);
	if (processor == PROCESSOR_NULL || processor->state == PROCESSOR_OFF_LINE) {
		return false;
	}
	if (current_thread()->sched_pri >= BASEPRI_RTQUEUES) {
		return false;   /* thread_bind is for threads below the real-time queues */
	}
	(void)thread_bind(processor);
	thread_block(THREAD_CONTINUE_NULL);   /* moves now, not at the next quantum */
	return true;
}

'''
     'void\nthread_bind_during_wakeup(thread_t thread, processor_t processor)\n{\n'),
])

edit('bsd/kern/proc_info.c', [
    ('/*\n * This is known to race with regards to the contents of the thread name; concurrent\n',
     '''/* zeus zeus-bind-enc=<cpu> (osfmk/kern/sched_prim.c). */
extern int zeus_bind_enc_cpu(void);
extern bool zeus_bind_self(int cpu);

'''
     '/*\n * This is known to race with regards to the contents of the thread name; concurrent\n'),
    ('\t\t\tbsd_setthreadname(ut, thread_tid(current_thread()), name_buf);\n\t\t}\n',
     '''\t\t\tbsd_setthreadname(ut, thread_tid(current_thread()), name_buf);
			const int bind_cpu = zeus_bind_enc_cpu();
			if (bind_cpu > 0 && strncmp(name_buf, "native-metal-encode", MAXTHREADNAMESIZE) == 0 &&
			    strncmp(proc_best_name(pself), "backboardd", 11) == 0) {
				const bool bound = zeus_bind_self(bind_cpu);
				printf("zeus-bind-enc: pid %d %s cpu%d\\n", proc_pid(pself), bound ? "bound to" : "NOT bound to", bind_cpu);
			}
		}
'''),
])

text = ''
for rel, (a, b) in edits.items():
    diff = difflib.unified_diff(a.splitlines(True), b.splitlines(True), f'a/{rel}', f'b/{rel}', n=3)
    text += f'diff --git a/{rel} b/{rel}\n' + ''.join(diff)
out.write_text('zeus zeus-bind-enc=<cpu>: backboardd\'s Metal encoder thread bound to one CPU. Generated by scripts/mk-bind-enc-patch.py.\n\n' + text)
print('ok', out, len(text))
