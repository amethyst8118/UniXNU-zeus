// The GPU restart after a hang, ported from sheng's gpuRestart (GpuPowerProbe.cpp, BSD-2-Clause-Patent). NativeAdrenoSubmit::recover
// calls it under the publish lock after it has ended any SMMU context fault: a6xx_recover's reset for a GPU whose GMU it does not
// power-cycle (GBIF drained including its GX side, RBBM_SW_RESET_CMD held for at least 100 us, then released), then hw_init on the same
// ring: registers, interrupt mask, SQE base, ring restart, SQE start, CP init waited idle, and CP_SET_SECURE_MODE 0 again once the zap
// shader has run (it stays loaded in TrustZone). The GMU keeps running and keeps the OOB GPU_SET vote. Without this hook a GPU fault
// froze the GPU for the rest of the boot (boot-bgra: hangs 137, restarts 0). [0] restarts, [1] the step a failed one stopped at,
// [2] its status, [3] RBBM_STATUS after the reset.
constexpr uint32_t kRbbmSwResetCmd = 0x43;
bool gZapRunning;
extern "C" {uint32_t native_gpu_restart[4];}
IOReturn gpuRestart(void *, NativeAdrenoRing *ring, uint32_t completed) {
  uint32_t *r = native_gpu_restart;
  r[0] = r[0] + 1;
  auto fail = [&](uint32_t step, IOReturn status) {r[1] = step; r[2] = uint32_t(status); return status ? status : kIOReturnIOError;};
  if (!ring) return fail(1, kIOReturnBadArgument);
  if (gpb_gdsc_on(reg(GPB_WIN_GPUCC, GPB_CC_GX_GDSCR))) gpuWr(CP_SQE_CNTL, 3);
  IOReturn status = ring->busHalt(true, 1000000);
  if (status) return fail(2, status);
  gpuWr(kRbbmSwResetCmd, 1); (void)gpuRd(kRbbmSwResetCmd); IODelay(1);
  IODelay(100);
  gpuWr(kRbbmSwResetCmd, 0); (void)gpuRd(kRbbmSwResetCmd); IODelay(1);
  r[3] = gpuRd(RBBM_STATUS);
  coreHwInit();
  gpuWr(kRbbmIntMask, kA730IntMask);
  gpuWr64(CP_SQE_INSTR_BASE, gBuffers[0].iova);
  status = ring->restart(completed);
  if (status) return fail(3, status);
  gpuWr64(kCpBvRptrAddr, gBuffers[2].iova + 8);
  gpuWr(CP_SQE_CNTL, 1);
  // The power-up list in buffer 3 stays as driverStart packed it.
  const NativeAdrenoCpInitConfig config = {gBuffers[0].iova, gBuffers[3].iova, 1};
  const NativeAdrenoRingClock clock = {nullptr, ringNow, nullptr};
  NativeAdrenoCpInit init;
  uint32_t fence = 0;
  status = init.run(&kRingIo, ring, &config, &fence, false);
  if (status) return fail(4, status);
  status = ring->idle(&clock, 1000000);
  if (status) return fail(5, status);
  if (gZapRunning) {
    uint32_t words[2] = {};
    if (AdrenoPM4Type7(0x66, 1, &words[0]) != AdrenoPM4Success) return fail(6, kIOReturnInternalError);
    status = ring->submitUnfenced(words, 2);
    if (!status) status = ring->idle(&clock, 1000000);
    if (status) return fail(6, status);
  }
  r[1] = 0; r[2] = 0;
  return kIOReturnSuccess;
}
// IO coherence, ported from sheng's coherenceProbe (GpuPowerProbe.cpp). Linux maps cached GPU BOs with IOMMU_CACHE when the Adreno
// is ADRENO_QUIRK_HAS_CACHED_COHERENT behind a dma-coherent SMMU. Without the proof, every imported IOSurface is cleaned at each
// submission and invalidated at completion (boot-fbgpu10: 52 GB cleaned, ~2.5 ms per submit, the UI at about 1 fps). A page of kernel
// memory is imported and mapped write-back, and both directions are proved against DRAM:
//   read:  the CPU stores new values over lines DRAM still holds old (seen dirty through an uncached mapping), the GPU copies the
//          page, and DRAM's copy must hold the new values, which only the CPU's caches had;
//   write: the CPU keeps clean lines of a page it read, the GPU copies other values over it, and plain cached loads must see them.
// Only both proofs set native_adreno_io_coherent. gpu-coherent=0 skips it (per-submission maintenance as before).
bool dramPage(uint64_t pa, uint32_t *out) {
  const vm_offset_t page = ml_io_map_unmappable(vm_offset_t(pa), 0x1000, 0x7 /* VM_WIMG_IO */);
  if (!page) return false;
  for (unsigned i = 0; i < 1024; ++i) out[i] = reinterpret_cast<const volatile uint32_t *>(page)[i];
  ml_io_unmap(page, 0x1000);
  return true;
}
// The driver's DRAM reader (native_adreno_dram_read32), after sheng's dramRead32 (GpuPowerProbe.cpp): one aligned word through an
// uncached kernel mapping. zeus never installed it, so every hang snapshot read its job's command buffers as deadbeef ("read 77 ib1
// 0 dwords, 77 unreadable", boot-poolclose) and the faulting address could not be found in them. The snapshot reads IBs a word at a
// time, so the last page stays mapped: a sequential read maps each page once instead of once per word.
IOLock *gDramReadLock;
vm_offset_t gDramReadVa;
uint64_t gDramReadPage = ~0ull;
int dramRead32(uint64_t pa, uint32_t *value) {
  if ((pa & 3) || !gDramReadLock) return 1;
  const uint64_t page = pa & ~uint64_t(0xfff);
  IOLockLock(gDramReadLock);
  if (page != gDramReadPage) {
    if (gDramReadVa) ml_io_unmap(gDramReadVa, 0x1000);
    gDramReadVa = ml_io_map_unmappable(vm_offset_t(page), 0x1000, 0x7 /* VM_WIMG_IO */);
    gDramReadPage = gDramReadVa ? page : ~0ull;
  }
  const bool ok = gDramReadVa != 0;
  if (ok) *value = *reinterpret_cast<const volatile uint32_t *>(gDramReadVa + vm_offset_t(pa & 0xfff));
  IOLockUnlock(gDramReadLock);
  return ok ? 0 : 1;
}
bool gpuCopyPage(uint64_t src, uint64_t dst) {
  uint32_t words[8] = {};
  if (AdrenoPM4Type7(0x75, 5, &words[0]) != AdrenoPM4Success || AdrenoPM4Type7(0x12, 0, &words[6]) != AdrenoPM4Success) return false;
  words[1] = 1024; words[2] = uint32_t(src); words[3] = uint32_t(src >> 32); words[4] = uint32_t(dst); words[5] = uint32_t(dst >> 32);
  return ringFence("coherence copy", words, 7);
}
// Table walk coherence, after the data proofs: a page is mapped while its table pages are published by ordering alone (no clean); the
// new leaf descriptor must still be dirty in a CPU cache, and the GPU copies through the mapping. The copy is right only if the SMMU's
// walk read the descriptor from the CPU's cache; then later maps clean no table line. A wrong walk faults the context: the fault is
// cleared and every table page is cleaned as before.
bool walkProbe(NativeAdrenoVm *vm) {
  constexpr uint64_t kBase = 0x18100000;
  constexpr size_t kBytes = 2 * 4096;
  uint8_t *buf = static_cast<uint8_t *>(IOMallocAligned(kBytes, 4096));
  if (!buf) {snprintf(native_gpu_walk_row, sizeof native_gpu_walk_row, "W nomem -> off"); return false;}
  volatile uint32_t *A = reinterpret_cast<volatile uint32_t *>(buf), *B = A + 1024;
  for (unsigned i = 0; i < 1024; ++i) {A[i] = 0x66660000u | i; B[i] = 0;}
  (void)NativeAdrenoMaintainOwnedPages(buf, kBytes, NativeAdrenoCleanInvalidate);
  NativeAdrenoMemory mem;
  IOReturn st = mem.importTask(kernel_task, uint64_t(uintptr_t(buf)), kBytes, 40, kBytes);
  uint64_t phys[2] = {};
  for (size_t j = 0; !st && j < mem.spanCount(); ++j)
    for (size_t at = 0; at < mem.spans()[j].bytes; at += 4096) phys[(mem.spans()[j].offset + at) / 4096] = mem.spans()[j].physical + at;
  static uint32_t words[1024];
  unsigned dirtyAt = 0, copied = 0;
  uint32_t fault[4] = {};
  for (unsigned attempt = 0; attempt < 8 && !st && phys[0] && phys[1] && !dirtyAt; ++attempt) {
    uint64_t handle = 0, pte = 0;
    native_adreno_walk_coherent[0] = 1;   // this map's table pages: ordering only
    st = vm->map(&mem, 0, kBase + attempt * 0x200000ull, 3, 1, 3, &handle);
    native_adreno_walk_coherent[0] = 0;
    if (st) break;
    if (vm->leafPhysical(phys[0], &pte) && dramPage(pte & ~0xfffull, words)) {
      const uint64_t inDram = uint64_t(words[(pte & 0xfff) / 4]) | uint64_t(words[(pte & 0xfff) / 4 + 1]) << 32;
      if ((inDram & 0x0000fffffffff000ull) != phys[0]) {
        dirtyAt = attempt + 1;
        const uint64_t iova = kBase + attempt * 0x200000ull;
        if (gpuCopyPage(iova, iova + 4096) && dramPage(phys[1], words))
          for (unsigned i = 0; i < 1024; ++i) copied += words[i] == (0x66660000u | i);
        (void)vm->faultState(fault);
      }
    }
    (void)vm->unmap(handle);
  }
  if (fault[0]) {
    uint32_t far[3] = {};
    if (NativeAdrenoGpuContext *context = NativeAdrenoGpuContextObject()) (void)context->clearFault(fault[0], far);
  }
  const bool pass = !st && dirtyAt && copied == 1024 && !fault[0];
  (void)NativeAdrenoMaintainOwnedPages(buf, kBytes, NativeAdrenoCleanInvalidate);
  (void)mem.release();
  IOFreeAligned(buf, kBytes);
  snprintf(native_gpu_walk_row, sizeof native_gpu_walk_row, "W d%u c%u f%x s%x -> %s", dirtyAt, copied, fault[0], uint32_t(st), pass ? "on" : "off");
  return pass;
}
unsigned gCoherenceAttempts;
void coherenceProbe(NativeAdrenoVm *vm) {
  uint32_t *k = native_gpu_coherence;
  unsigned wanted = 1;
  PE_parse_boot_argn("gpu-coherent", &wanted, sizeof wanted);
  if (!wanted || !vm || !&native_adreno_io_coherent || !&native_adreno_walk_coherent) {
    snprintf(native_gpu_coherence_row, sizeof native_gpu_coherence_row, "H skip (arg %u vm %d)", wanted, vm != nullptr);
    printf("ZEUS GPU: coherence %s\n", native_gpu_coherence_row);
    return;
  }
  constexpr uint64_t kIova = 0x18000000;
  constexpr size_t kBytes = 4 * 4096;
  uint8_t *buf = static_cast<uint8_t *>(IOMallocAligned(kBytes, 4096));
  NativeAdrenoMemory mem;
  uint64_t handle = 0;
  IOReturn st = buf ? mem.importTask(kernel_task, uint64_t(uintptr_t(buf)), kBytes, 40, kBytes) : kIOReturnNoMemory;
  k[0] = 1;
  if (!st) {k[0] = 2; st = vm->map(&mem, 0, kIova, 3, 1, 3, &handle);}
  uint64_t phys[4] = {};
  for (size_t j = 0; !st && j < mem.spanCount(); ++j)
    for (size_t at = 0; at < mem.spans()[j].bytes; at += 4096) phys[(mem.spans()[j].offset + at) / 4096] = mem.spans()[j].physical + at;
  static uint32_t words[1024];
  bool pass = false;
  if (!st && phys[0] && phys[1] && phys[2] && phys[3]) {
    k[0] = 3;
    volatile uint32_t *S = reinterpret_cast<volatile uint32_t *>(buf), *D = S + 1024, *R = S + 2048, *T = S + 3072;
    // read direction: S's new words must still be dirty in a CPU cache (DRAM holding the old ones, at least 48 of 64 lines) when the
    // GPU copies S; the setup repeats until they are, up to eight times.
    bool dirty = false;
    for (unsigned attempt = 0; attempt < 8 && !st && !dirty; ++attempt) {
      gCoherenceAttempts = attempt + 1;
      for (unsigned i = 0; i < 1024; ++i) {S[i] = 0x11110000u | i; D[i] = 0; R[i] = 0x33330000u | i; T[i] = 0x44440000u | i;}
      st = NativeAdrenoMaintainOwnedPages(buf, kBytes, NativeAdrenoCleanInvalidate);
      for (unsigned i = 0; i < 1024; ++i) S[i] = 0x22220000u | i;
      __asm__ volatile("dsb sy" ::: "memory");
      k[1] = 0;
      if (!st && dramPage(phys[0], words)) for (unsigned i = 0; i < 1024; i += 16) k[1] += words[i] == (0x11110000u | i);
      dirty = k[1] >= 48;
    }
    if (!st && dirty) {
      k[0] = 4;
      if (gpuCopyPage(kIova, kIova + 4096) && dramPage(phys[1], words)) {
        k[0] = 5;
        for (unsigned i = 0; i < 1024; ++i) {k[2] += words[i] == (0x22220000u | i); k[3] += words[i] == (0x11110000u | i);}
      }
    }
    // write direction: T written back and kept (clean, resident), then read so its lines are present when the GPU writes
    if (!st && k[0] == 5) st = NativeAdrenoMaintainOwnedPages(const_cast<uint32_t *>(T), 4096, NativeAdrenoClean);
    uint32_t touch = 0;
    for (unsigned i = 0; i < 1024; ++i) touch += T[i];
    __asm__ volatile("dsb sy" ::: "memory");
    if (!st && k[0] == 5 && gpuCopyPage(kIova + 8192, kIova + 12288)) {
      k[0] = 6;
      for (unsigned i = 0; i < 1024; ++i) k[4] += T[i] == (0x33330000u | i);
      if (dramPage(phys[3], words)) for (unsigned i = 0; i < 1024; ++i) k[5] += words[i] == (0x33330000u | i);
    }
    (void)touch;
    pass = k[0] == 6 && k[1] >= 48 && k[2] == 1024 && k[4] == 1024 && k[5] == 1024;
  }
  k[6] = uint32_t(st);
  if (handle) (void)vm->unmap(handle);
  // Whatever the result, no line of these pages stays in a CPU cache (a stale clean copy would outlive the free).
  if (buf) (void)NativeAdrenoMaintainOwnedPages(buf, kBytes, NativeAdrenoCleanInvalidate);
  (void)mem.release();
  if (buf) IOFreeAligned(buf, kBytes);
  k[7] = pass;
  native_adreno_io_coherent = pass ? 1 : 0;
  unsigned walk = 1;
  PE_parse_boot_argn("gpu-walk", &walk, sizeof walk);
  native_adreno_walk_coherent[0] = pass && walk && walkProbe(vm) ? 1 : 0;
  snprintf(native_gpu_coherence_row, sizeof native_gpu_coherence_row, "H d%u/64 a%u r%u/%u w%u/%u s%x k%u -> %s", k[1], gCoherenceAttempts,
           k[2], k[3], k[4], k[5], k[6], k[0], pass ? "on" : "off");
  printf("ZEUS GPU: coherence %s; walk %s\n", native_gpu_coherence_row, pass && walk ? native_gpu_walk_row : "not tried");
}
void openCpAperture() {
  uint64_t answer = 0;
  const int64_t available = scmCall("CP aperture available", 0x42000601, 1, 0x02000000u | (0x0cu << 8) | 0x1bu, 0, 0, &answer);
  // The driver picks CP table switching (mode 2) from these words; unset they read as "unavailable" and every change of process drains
  // the GPU (mode 1: gpum34 3255 switches). As sheng: [0] availability, [1] the call's x0. gpu-ttbr=1 keeps mode 1.
  if (&native_adreno_cp_aperture) native_adreno_cp_aperture[0] = available ? 0x80000000u | uint32_t(available) : uint32_t(answer);
  if (available || !answer) {
    if (&native_adreno_cp_aperture) native_adreno_cp_aperture[1] = 0xffffffffu;
    printf("ZEUS GPU: CP aperture call unavailable\n");
    return;
  }
  const int64_t opened = scmCall("CP aperture", 0x42000c1b, 4, 0xffff0000u, 0xffffffffu, 0xffffffffu, &answer, 0xffffffffu);
  if (&native_adreno_cp_aperture) native_adreno_cp_aperture[1] = uint32_t(opened);
}
// gpu-metal=1 (with gpu-power=8): after DRIVER PUBLISHED, publish the staged accelerator for Metal's device discovery, as sheng's
// publishMetal. Stages: 1 started, 2 IOAcceleratorES (136 bytes) found, 3 own class registered, 4 object made with its keys, 5 published.
// No Metal plugin bundle is installed on zeus yet, so discovery can find the accelerator but has nothing to load.
unsigned gMetal;
uint32_t gMetalStage;
int gMetalKext = -99, gMetalStatus;
void publishMetal() {
  gMetalStage = 1;
  [&] {
    if (!native_adreno_accelerator_static_init || !native_adreno_accelerator_allocate || !native_adreno_accelerator_instance_size) {
      gMetalStatus = kIOReturnUnsupported;
      return;
    }
    gMetalKext = OSKextLoadKextWithIdentifier("com.apple.iokit.IOGPUFamily");
    if (gMetalKext) {gMetalStatus = gMetalKext; return;}
    const OSSymbol *name = OSSymbol::withCString("IOAcceleratorES");
    const OSMetaClass *parent = name ? OSMetaClass::getMetaClassWithName(name) : nullptr;
    OSSafeReleaseNULL(name);
    if (!parent || parent->getClassSize() != 136) {gMetalStatus = kIOReturnNotFound; return;}
    gMetalStage = 2;
    void *handle = OSMetaClass::preModLoad(g_kernel_kmod_info.name);
    if (!handle) {gMetalStatus = kIOReturnNoResources; return;}
    native_adreno_accelerator_static_init();
    gMetalStatus = OSMetaClass::postModLoad(handle);
    if (gMetalStatus) return;
    if (native_adreno_accelerator_instance_size() != 136) {gMetalStatus = kIOReturnInvalid; return;}
    gMetalStage = 3;
    IOService *accelerator = native_adreno_accelerator_allocate();
    if (!accelerator) {gMetalStatus = kIOReturnNoMemory; return;}
    if (!accelerator->init()) {accelerator->release(); gMetalStatus = kIOReturnError; return;}
    // The keys the original _MTLRegisterDevices reads. The plugin name is ours; no Apple device identity is claimed.
    // metal-native=1 (docs/NATIVE-METAL-PLAN.md): the native driver (ios-sweet's SweetNativeMetal frontend on Gallium freedreno,
    // built as ZeusNativeMetal.bundle in the GPU add-on) instead of the metal2vulkan plug-in. Both bundles ship; this picks one.
    uint32_t nativeMetal = 0;
    PE_parse_boot_argn("metal-native", &nativeMetal, sizeof nativeMetal);
    accelerator->setProperty("MetalPluginName", nativeMetal == 1 ? "ZeusNativeMetal" : "NativeAdrenoMetal");
    accelerator->setProperty("MetalPluginClassName", nativeMetal == 1 ? "SweetNativeMetalDevice" : "NativeAdrenoMetalDevice");
    // patches/xnu/zzw-native-adreno-sandbox-grant.patch: the original sandbox profiles name no class of this driver.
    accelerator->setProperty("NativeSandboxGrantProcess", "*");
    gMetalStage = 4;
    if (!accelerator->attach(IOService::getPlatform())) {accelerator->release(); gMetalStatus = kIOReturnNotAttached; return;}
    accelerator->registerService();
    gMetalStage = 5;
  }();
  printf("ZEUS GPU: metal stage %u status %x kext %x%s\n", gMetalStage, unsigned(gMetalStatus), unsigned(gMetalKext),
         gMetalStage == 5 ? " (ACCELERATOR PUBLISHED)" : "");
}
// Is the probe daemon (launchd job org.unixnu.adrenoprobed, the unified-log export) alive? As sheng's scanProcess (GpuPowerProbe.cpp), with
// the counts on the caller's stack: the kernel's __DATA has no room for new statics.
struct ProcScan {uint32_t total, daemon, launchd;};
int scanProcess(void *proc, void *arg) {
  ProcScan *s = static_cast<ProcScan *>(arg);
  s->total = s->total + 1;
  const char *name = proc_name_address(proc);
  if (name && !strncmp(name, "adrenoprobed", 12)) s->daemon = s->daemon + 1;
  if (name && !strcmp(name, "launchd")) s->launchd = s->launchd + 1;
  return 0;   // PROC_RETURNED: keep iterating
}
