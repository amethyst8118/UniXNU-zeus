// zeus (SM8450, Adreno 730) GPU power probe, staged like sheng's GpuPowerProbe.cpp. Boot argument gpu-power=<n>, default 0 (off):
//   1  read only: GCC GPU branches, GPUCC GDSCs and clocks, GPU SMMU global space and RBBM_STATUS, each only if the stage before
//      showed its prerequisite on (ZeusGpuPowerBoard.h); then the GMU clock tree and the AOP command DB header
//   2  as 1, plus the one write Linux's gcc-sm8450 probe makes: gcc_gpu_cfg_ahb_clk on, if it is off
//   3  as 2, plus, if CX is off: the gpu_cc_cx_gdsc enable sequence, gpu_cc_ahb_clk and the SMMU vote clock. GX is never touched.
//   4  as 3, then the GMU clocks without the GPU PLLs: GPLL0 GPU votes, GCC GPU branches, GMU 200 MHz and hub 150 MHz from the GPLL0
//      300 MHz tap (waipio values, order of diting's DitingAdrenoEnableCxClocks; same recipe passed on negroni's SM8450), the GPUCC CX
//      branches, then a read of the GMU always-on counter. The GMU stays in reset and no firmware is loaded.
//   5  as 4, then the GMU cold start: its own SMMU context (bank 1, SID 5 mask 0x400, native 4K tables), RSC/PDC setup, the private
//      gmu_gen70000.bin embedded at build time, CM3 release, FW_INIT_RESULT and HFI ready. No RPMh vote and no GX. Register facts and
//      the HFI table: diting DitingAdrenoGmu.c/DitingAdrenoHfi.c (BSD-2-Clause-Patent); GMU id 0x07030100 for chip 0x07030001 (gen7-0-1).
//   6  as 5, then HFI messages: performance table (zeus DT levels, votes from the command DB), the A730 bandwidth table, CORE_FW_START, START,
//      a vote for the lowest level (220 MHz), and OOB GPU_SET, which makes the GMU power GX. The request stays held. No GPU register is written.
//   7  as 6, then the command processor: GPU SMMU context (bank 0, SIDs 0 and 1, mask 0x400), a730_sqe.fw, A730 hardware init without clock gating or
//      CP protection, CP_ME_INIT, the zap shader through TrustZone (PAS image 13, zeus carve-out 0x8b91a000), CP_SET_SECURE_MODE 0 and a CP_MEM_WRITE
//      into a scratch page, which the CPU then reads back. Private firmware is embedded at build time.
//   8  as 6, then sheng's Adreno driver core on the A730: its GPU context and buffers, ring, CP init, zap, interrupt, timer and submit object,
//      then native_adreno_publish. A one-ring start without clock gating, CP protection or preemption; with gpu-metal=1 it then publishes the staged accelerator for Metal discovery (publishMetal).
// A read of an unclocked block can reset the phone, so the log says what comes next and waits before each new block: the last line
// on the USB log (zeus_usbeth_host.py) names the block. The run starts late (gpu-power-delay, seconds) so that link is up.
