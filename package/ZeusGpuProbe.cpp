void cleanCache(const void *memory, size_t bytes) {
  uint64_t ctr;
  __asm__ volatile("mrs %0, ctr_el0" : "=r"(ctr));
  const uintptr_t line = 4u << ((ctr >> 16) & 15);
  const uintptr_t end = reinterpret_cast<uintptr_t>(memory) + bytes;
  for (uintptr_t at = reinterpret_cast<uintptr_t>(memory) & ~(line - 1); at < end; at += line) __asm__ volatile("dc civac, %0" : : "r"(at) : "memory");
  __asm__ volatile("dsb sy" : : : "memory");
}
bool dmaAlloc(Dma &m, size_t bytes) {
  m.keep = IOBufferMemoryDescriptor::inTaskWithOptions(kernel_task, IOOptionBits(kIODirectionInOut) | IOOptionBits(kIOMemoryPhysicallyContiguous) |
                                                       IOOptionBits(kIOMemoryMapperNone), bytes, 4096);
  if (!m.keep) return false;
  IOByteCount contiguous = 0;
  m.cpu = static_cast<uint8_t *>(m.keep->getBytesNoCopy());
  m.pa = m.keep->getPhysicalSegment(0, &contiguous, kIOMemoryMapperNone);
  m.bytes = bytes;
  if (!m.cpu || !m.pa || (m.pa & 4095) || contiguous < bytes || m.pa + bytes > (1ULL << 36)) return false;
  bzero(m.cpu, bytes);
  cleanCache(m.cpu, bytes);
  return true;
}
uint64_t *nextTable(uint64_t *parent, unsigned index) {
  if (!parent[index]) {
    if (gTablesUsed == kTablePages) return nullptr;
    parent[index] = (gTables.pa + uint64_t(gTablesUsed++) * 4096) | 3;
  }
  return reinterpret_cast<uint64_t *>(gTables.cpu + ((parent[index] & ~4095ULL) - gTables.pa));
}
bool mapRange(uint32_t iova, const Dma &m, uint64_t attributes) {
  uint64_t *root = reinterpret_cast<uint64_t *>(gTables.cpu);
  for (size_t at = 0; at < m.bytes; at += 4096) {
    const uint32_t va = iova + uint32_t(at);
    uint64_t *l2 = nextTable(root, (va >> 30) & 3);
    uint64_t *l3 = l2 ? nextTable(l2, (va >> 21) & 511) : nullptr;
    if (!l3) return false;
    l3[(va >> 12) & 511] = (m.pa + at) | attributes;
  }
  return true;
}
